#pragma once

#include <juce_audio_formats/juce_audio_formats.h>
#include <juce_audio_basics/juce_audio_basics.h>

namespace click
{

/** Access to the ten stock click samples that are compiled into the binary.

    The samples are generated by tools/generate_clicks.py and embedded via
    juce_add_binary_data, so the plugin has no runtime file dependencies.
*/
namespace library
{
    /** Number of stock clicks shipped with the plugin. */
    inline constexpr int numStockClicks = 10;

    /** Display name for a stock click, e.g. "Wood Block". */
    juce::String getStockName (int index);

    /** Filename of the embedded resource backing a stock click. */
    juce::String getStockFileName (int index);

    /** Decodes a stock click into `destination`.

        @returns the sample rate of the decoded audio, or 0.0 on failure.
    */
    double loadStockClick (int index, juce::AudioBuffer<float>& destination);

    /** Decodes an arbitrary audio file chosen by the user.

        @returns the sample rate of the decoded audio, or 0.0 on failure.
    */
    double loadFile (const juce::File& file,
                     juce::AudioBuffer<float>& destination,
                     juce::AudioFormatManager& formatManager);

} // namespace library

} // namespace click
